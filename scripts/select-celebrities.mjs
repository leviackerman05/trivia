// --- dedup collisions with the existing pool -------------------------------
const existingKeys = new Set(existing.map((e) => norm(e.name)));
const available = pool.filter((c) => !existingKeys.has(norm(c.name)));

// --- bucket the candidates and take the top-N per (region, genre) by sitelinks
const buckets = new Map();
for (const c of available) {
  const key = `${c.region}\u0000${c.genre}`;
  if (!buckets.has(key)) buckets.set(key, []);
  buckets.get(key).push(c);
}
const selected = [];
for (const [region, genres] of Object.entries(USE)) {
  for (const [genre, take] of Object.entries(genres)) {
    const list = (buckets.get(`${region}\u0000${genre}`) ?? []).sort(
      (a, b) => b.sitelinks - a.sitelinks
    );
    const chosen = list.slice(0, take);
    if (chosen.length < take) {
      console.warn(`SHORT ${region}/${genre}: wanted ${take}, have ${chosen.length}`);
    }
    selected.push(
      ...chosen.map((c) => ({
        ...c,
        profession: PROFESSION_FIX[c.name] ?? c.profession,
        nationality: NATIONALITY_FIX[c.name] ?? c.nationality,
        ageRange: AGERANGE_FIX[c.name] ?? c.ageRange,
      }))
    );
  }
}

// --- write outputs ----------------------------------------------------------
const selectedPath = new URL('./tmp/selection.json', import.meta.url);
const supplementsPath = new URL('./tmp/supplements.json', import.meta.url);
writeFileSync(selectedPath, JSON.stringify(selected, null, 2) + '\n');
writeFileSync(
  supplementsPath,
  JSON.stringify([...SUPPLEMENTS, ...extraSupplements], null, 2) + '\n'
);

